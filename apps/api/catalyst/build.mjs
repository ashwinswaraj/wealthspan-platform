// Bundles each Catalyst function's src/entry.ts into index.js. Run: pnpm --filter @jobrio/api build:catalyst
import { build } from "esbuild";

const common = ["express", "zcatalyst-sdk-node"];
const fns = { finance: [], chat: [], files: ["exceljs", "docx", "pdfkit"] };

for (const [name, extra] of Object.entries(fns)) {
  await build({
    entryPoints: [`catalyst/functions/${name}/src/entry.ts`],
    outfile: `catalyst/functions/${name}/index.js`,
    bundle: true, platform: "node", target: "node22", format: "cjs",
    external: [...common, ...extra],
    banner: { js: "// GENERATED by pnpm build:catalyst from src/entry.ts - do not edit" },
  });
}
